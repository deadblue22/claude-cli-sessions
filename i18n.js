  const DEFAULT = 'en';
  // 'zh', 'zh-TW', 'zh-Hans-CN' … → 'zh-CN'; exact match otherwise; unknown → null
  function match(tag) {
    tag = String(tag || '').trim();
    if (!tag) return null;
    if (DICT[tag]) return tag;
    const base = tag.toLowerCase().split(/[-_]/)[0];
    if (base === 'zh') return 'zh-CN';
    return Object.keys(DICT).find(k => k.toLowerCase().split('-')[0] === base) || null;
  }
  // First supported entry of a list of language tags (navigator.languages or Accept-Language)
  function pick(tags) {
    for (const t of tags || []) { const m = match(String(t).split(';')[0]); if (m) return m; }
    return DEFAULT;
  }
  function t(lang, key, vars) {
    const s = (DICT[lang] && DICT[lang][key]) ?? DICT[DEFAULT][key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
  }
  const api = { DICT, DEFAULT, match, pick, t, langs: () => Object.keys(DICT).map(k => [k, DICT[k]._name]) };
